#!/usr/bin/env python
"""
Generates a C++ include file with linker /export pragmas for forwarding to a steam_api64 proxy.
Emits one #pragma per export. Requires pefile: https://github.com/erocarrera/pefile

Usage:
    generate_steam_proxy.py [-o <output>] [-f <forward>] <dll>
"""
import sys
import argparse
import pefile

DEFAULT_OUTPUT_FILE = "steam_forwards.inc"
DEFAULT_FORWARD_TARGET = "steam_api64_real"

def main() -> int:
    parser = argparse.ArgumentParser(description="")
    parser.add_argument("dll", help="the dll file to parse")
    parser.add_argument("-o", "--output", default=DEFAULT_OUTPUT_FILE, help="the include file to generate")
    parser.add_argument("-f", "--forward", default=DEFAULT_FORWARD_TARGET, help="the target to forward to")
    args = parser.parse_args()

    pe = pefile.PE(args.dll)
    symbols = pe.DIRECTORY_ENTRY_EXPORT.symbols
    lines = [
        "// GENERATED by generate_steam_proxy.py.",
        f"// Source: {args.dll}",
        f"// {len(symbols)} exports forwarded to the renamed target ({args.forward}.dll)"
    ]
    seen = set()
    dupes = 0
    for symbol in symbols:
        if symbol.name:
            name = (symbol.name.decode(errors="replace") if isinstance(symbol.name, bytes) else str(symbol.name))
        else:
            name = f"ord{symbol.ordinal}"

        if name in seen:
            dupes += 1
            print(f"  NOTE: skipping duplicate export name {name} (ordinal {symbol.ordinal})", file=sys.stderr)
            continue

        seen.add(name)
        lines.append(f'#pragma comment(linker, "/export:{name}={args.forward}.{name},@{symbol.ordinal}")')

    with open(args.output, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")

    print(f"wrote {args.output}: {len(seen)} forward pragmas ({dupes} duplicates dropped)")
    return 0

if __name__ == "__main__":
    sys.exit(main())
